import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Category, Playbook, RouteEntry, StrategyId } from '../../shared/types.ts';
import { CATEGORY_LABELS, STRATEGY_LABELS } from '../../shared/types.ts';
import { PLAYBOOK_DIR } from './paths.ts';

export const CATEGORIES: Category[] = ['exception', 'deploy-regression', 'resource', 'error-rate', 'synthetic', 'third-party', 'infra', 'security', 'unknown'];
export const CODE_CATEGORIES: Category[] = ['exception', 'deploy-regression', 'resource', 'error-rate', 'synthetic', 'unknown'];

const CANDIDATES: Record<Category, StrategyId[]> = {
  exception: ['keyword-grep', 'stack-trace-first', 'recent-deploy-diff'],
  'deploy-regression': ['keyword-grep', 'recent-deploy-diff', 'stack-trace-first'],
  resource: ['keyword-grep', 'dependency-trace', 'recent-deploy-diff'],
  'error-rate': ['keyword-grep', 'stack-trace-first', 'recent-deploy-diff'],
  synthetic: ['keyword-grep', 'runbook-lookup', 'stack-trace-first'],
  'third-party': ['keyword-grep', 'runbook-lookup'],
  infra: ['keyword-grep', 'runbook-lookup'],
  security: ['runbook-lookup'],
  unknown: ['keyword-grep', 'stack-trace-first', 'runbook-lookup'],
};

export const GUARDRAILS = [
  'G1 · Never take autonomous action on a suspected security incident — gather context and page security on-call.',
  'G2 · Every code change ships as a pull request with a regression test that fails before and passes after. Humans approve merges.',
  'G3 · Never change infrastructure directly; leave a diagnostic note or escalate.',
  'G4 · Escalate P1/P2 incidents to the owning team when the root cause is not found within the step budget.',
  'G5 · Learned triage rules may only hold or suppress alert types with zero matching real incidents in the evidence window.',
];

/** Version 1: the hand-written starter playbook a team would begin with. Deliberately naive. */
export function seedPlaybook(): Playbook {
  const routing = Object.fromEntries(
    CATEGORIES.map((c) => {
      const entry: RouteEntry = {
        strategy: CANDIDATES[c][0],
        candidates: CANDIDATES[c],
        confidence: c === 'security' ? 1 : 0.2,
        race: CODE_CATEGORIES.includes(c),
        reason: c === 'security' ? 'Guardrail G1' : 'Starter default: no outcome data yet',
      };
      return [c, entry];
    }),
  ) as Record<Category, RouteEntry>;
  return {
    version: 1,
    createdAt: Date.now(),
    guardrails: GUARDRAILS,
    fingerprint: { normalizeNumbers: false, stripHostIds: false },
    triageRules: [],
    correlations: [],
    routing,
    knowledge: [],
    stats: {},
    exploration: 0.35,
    changelog: [{ version: 1, at: Date.now(), items: ['Starter playbook: exact-title de-duplication, keyword search everywhere, race strategies on uncertain P1/P2 code incidents.'] }],
  };
}

export function renderPlaybook(pb: Playbook): string {
  const L: string[] = [];
  L.push(`# Devin Oncall Playbook — v${pb.version}`);
  L.push('');
  L.push(pb.version === 1 ? '_Starter playbook (human-authored)._' : `_Auto-generated by the retrospective after run ${pb.version - 1}. Parent: v${pb.parentVersion}._`);
  L.push('');
  L.push('## Guardrails (human-authored, never auto-edited)');
  for (const g of pb.guardrails) L.push(`- ${g}`);
  L.push('');
  L.push('## Triage');
  L.push('');
  L.push('### Fingerprinting');
  L.push(
    pb.fingerprint.normalizeNumbers
      ? `- Normalize host IDs, numbers and order IDs before de-duplicating _(learned v${pb.fingerprint.addedIn})_`
      : '- Exact title match only',
  );
  L.push('');
  L.push('### Noise rules');
  if (!pb.triageRules.length) L.push('- _none yet_');
  for (const r of pb.triageRules) {
    const m = [r.match.envNot ? `env ≠ ${r.match.envNot}` : '', r.match.monitor ? `monitor = \`${r.match.monitor}\`` : '', r.match.tag ? `tag ${r.match.tag[0]}=${r.match.tag[1]}` : '']
      .filter(Boolean)
      .join(' AND ');
    L.push(`- **${r.id}** ${r.kind === 'hold' ? `HOLD ${r.holdMinutes} min, investigate only if still firing` : 'SUPPRESS'} when ${m} — ${r.reason} _(v${r.addedIn}; evidence: ${r.evidence[0]})_`);
  }
  L.push('');
  L.push('### Correlation rules');
  if (!pb.correlations.length) L.push('- _none yet_');
  for (const c of pb.correlations) {
    L.push(`- **${c.id}** group into one incident (\`${c.groupKey}\`): ${c.fingerprints.map((f) => `\`${f.split('|').slice(0, 2).join(' · ')}\``).join(', ')} — ${c.reason} _(v${c.addedIn})_`);
  }
  L.push('');
  L.push('## Investigation routing');
  L.push('');
  L.push('| Category | Preferred strategy | Confidence | Race? | Record |');
  L.push('|---|---|---|---|---|');
  for (const c of CATEGORIES) {
    const r = pb.routing[c];
    const s = pb.stats[c] ?? {};
    const rec = Object.entries(s)
      .map(([k, v]) => `${STRATEGY_LABELS[k as StrategyId]} ${v!.wins}/${v!.trials} (${(v!.totalMin / Math.max(1, v!.trials)).toFixed(1)}m)`)
      .join('; ');
    L.push(`| ${CATEGORY_LABELS[c]} | ${STRATEGY_LABELS[r.strategy]} | ${Math.round(r.confidence * 100)}% | ${r.race ? 'yes' : 'no'} | ${rec || '—'} |`);
  }
  L.push('');
  L.push(`Exploration rate: ${Math.round(pb.exploration * 100)}%`);
  L.push('');
  L.push('## Knowledge');
  if (!pb.knowledge.length) L.push('- _none yet_');
  for (const k of pb.knowledge) L.push(`- **${k.id}** \`${k.bugId}\` → \`${k.file}\`: ${k.hint} _(v${k.addedIn}, matches ${k.fingerprints.length} alert signature(s))_`);
  L.push('');
  L.push('## Changelog');
  for (const c of [...pb.changelog].reverse()) {
    L.push(`### v${c.version}`);
    for (const i of c.items) L.push(`- ${i}`);
  }
  return L.join('\n');
}

export function savePlaybook(pb: Playbook): void {
  mkdirSync(PLAYBOOK_DIR, { recursive: true });
  const md = renderPlaybook(pb);
  writeFileSync(join(PLAYBOOK_DIR, `v${pb.version}.json`), JSON.stringify(pb, null, 2));
  writeFileSync(join(PLAYBOOK_DIR, `v${pb.version}.md`), md);
  writeFileSync(join(PLAYBOOK_DIR, 'playbook.md'), md);
}

export function loadPlaybooks(): Playbook[] {
  if (!existsSync(PLAYBOOK_DIR)) return [];
  return readdirSync(PLAYBOOK_DIR)
    .filter((f) => /^v\d+\.json$/.test(f))
    .map((f) => JSON.parse(readFileSync(join(PLAYBOOK_DIR, f), 'utf8')) as Playbook)
    .sort((a, b) => a.version - b.version);
}
